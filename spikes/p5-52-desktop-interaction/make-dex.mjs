#!/usr/bin/env node
// P5-52 spike, throwaway: loads the built-in content with the mod's own loader
// and writes mod/hooks/dex.ts, one thumbnail Svg and one detail Svg per
// Modster, so the spike pane can test a dex grid with real art.
//
//   node spikes/p5-52-desktop-interaction/make-dex.mjs   (Node 22.18+)
import '../../tools/ts-resolve.mjs'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const { loadContent } = await import('../../plugin/hooks/content/index.ts')
const { desktopSheetSvg, pixelsToSvg, spriteRgba } = await import('../../plugin/hooks/render/index.ts')

const root = fileURLToPath(new URL('../../plugin/content', import.meta.url))
const reader = {
  async listFolders(path) {
    if (!existsSync(path)) return []
    return readdirSync(path, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name)
  },
  async readText(path) {
    return existsSync(path) ? readFileSync(path, 'utf8') : undefined
  },
  async readBase64(path) {
    return existsSync(path) ? readFileSync(path).toString('base64') : undefined
  },
}

// A desktop sheet is about 4× finer than a terminal sprite (0045 point 9).
// One Svg per Modster: a hooks module file is read only up to 1 MiB, so the
// detail view scales this one up with the Svg's width and height
const THUMB = { sheet: 0.5, sprite: 2 }

function svgOf({ modster, sprite, desktop }, scale) {
  if (desktop) return desktopSheetSvg(desktop, { scale: scale.sheet, fps: modster.desktopSprite?.fps ?? 4 })
  const frames = spriteRgba(sprite).map((rgba) => ({ width: sprite.width, height: sprite.height, rgba }))
  return pixelsToSvg(frames, { scale: scale.sprite, fps: modster.sprite?.fps ?? 4 })
}

function sizeOf({ sprite, desktop }, scale) {
  return desktop ? { width: desktop.width * scale.sheet, height: desktop.height * scale.sheet } : { width: sprite.width * scale.sprite, height: sprite.height * scale.sprite }
}

const content = await loadContent(reader, root)
const entries = [...content.modsters.values()]
  .filter((loaded) => loaded.modster.dex)
  .sort((a, b) => a.modster.dex.number - b.modster.dex.number)
  .map((loaded) => {
    const { id, name, rarity, dex } = loaded.modster
    return {
      id,
      name,
      number: dex.number,
      rarity,
      types: dex.types,
      category: dex.category,
      entry: dex.entry,
      art: loaded.desktop ? 'desktop sheet' : 'terminal sprite',
      thumb: svgOf(loaded, THUMB),
      ...sizeOf(loaded, THUMB),
    }
  })

const total = entries.reduce((sum, e) => sum + e.thumb.length, 0)
const out = fileURLToPath(new URL('./mod/hooks/dex.ts', import.meta.url))
writeFileSync(
  out,
  `// Generated by make-dex.mjs (P5-52 spike). Don't edit.\n` +
    `export interface DexEntry { id: string; name: string; number: number; rarity: string; types: string[]; category: string; entry: string; art: string; thumb: string; width: number; height: number }\n` +
    `export const DEX: DexEntry[] = ${JSON.stringify(entries, null, 1)}\n` +
    `export const THUMB_CHARS = ${total}\n`,
)
console.log(`${entries.length} Modsters, ${total} characters of thumbnails, largest ${Math.max(...entries.map((e) => e.thumb.length))}`)
